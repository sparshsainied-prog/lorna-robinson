/* lornarobinson.uk: shared script for every page.
   Page builders: do not edit this file. Page scripts go in js/<page>.js and use window.site (API below).

   window.site
     .still            true when the reader prefers reduced motion (tracked live)
     .clamp(v)         0..1
     .ease(t)          smoothstep
     .easeIn(t)        t*t
     .onFrame(fn)      fn(y, vh) once per frame when the page has scrolled or resized (one rAF-throttled listener)
     .offFrame(fn)
     .progress(el, from, to)
                       0..1 for where el is in the viewport: 0 when el's top is `from` viewport-heights below the
                       top edge, 1 when it is `to` viewport-heights. Defaults: from 1 (just entering), to 0 (at the top).
     .pin(section, fn) for a tall section with a sticky stage inside: fn(p) with p = scrolled / (height - vh), 0..1,
                       called only when p changes; under reduced motion fn(1) is called once and never again.
     .drift(el, px)    the element eases `px` pixels (negative = upward) across its travel through the viewport
     .track(el, from, to, fn)
                       fn(p, el) each frame with p = progress(el, from, to), only when p changes; under reduced
                       motion fn(1) once (and again if the preference changes). Returns an unregister function.
     .prop(el, from, to, name = '--p')
                       writes progress(el, from, to) into a CSS custom property on el, so the page's CSS can
                       drive a transform from it (calc against var(--p)); 1 under reduced motion
     .move(el, x, y, from = 1, to = .6)
                       el travels from an offset of (x, y) px to rest at 0 as it rises from `from` to `to`
     .shelve(row, items, stagger = .14)
                       items (default: row's children) are set down one after another, left to right, as the row
                       comes up: each gets --set 0..1 and class "set"; css/site.css turns --set into a translateY
                       of --lift (default -1.2rem: held a little above, set down). Reduced motion: --set 1.
   Shared quiet behaviours applied by this file (no page code needed):
     the register    every h2.cap in main (and any .cap[data-register]) prints with a faint second impression,
                     offset up and left, that comes into register as the heading rises into view (--reg 0..1).
                     Opt out with data-register="off" on the heading. Set --reg-ink on the heading or section to
                     print the ghost in another colour (default currentColor).
     book to book    in .nextprev the Previous link arrives from 14px left and Next from 14px right.
   Under reduced motion, or without JavaScript, css/site.css freezes .fx elements at their finished state. */
(() => {
  const html = document.documentElement;
  html.classList.add('js');
  const mq = matchMedia('(prefers-reduced-motion: reduce)');
  const clamp = v => v < 0 ? 0 : v > 1 ? 1 : v;
  const ease = t => t * t * (3 - 2 * t);
  const easeIn = t => t * t;

  /* ---- one scroll listener for the page ---- */
  const subs = new Set();
  let ticking = false, vh = innerHeight;
  function frame() {
    ticking = false;
    const y = scrollY;
    subs.forEach(fn => fn(y, vh));
  }
  function ask() { if (!ticking) { ticking = true; requestAnimationFrame(frame); } }
  addEventListener('scroll', ask, { passive: true });
  addEventListener('resize', () => { vh = innerHeight; subs.forEach(fn => fn.measure && fn.measure()); ask(); });
  addEventListener('load', () => { subs.forEach(fn => fn.measure && fn.measure()); ask(); });

  const site = {
    get still() { return mq.matches; },
    clamp, ease, easeIn,
    onFrame(fn) { subs.add(fn); if (fn.measure) fn.measure(); fn(scrollY, vh); },
    offFrame(fn) { subs.delete(fn); },
    progress(el, from = 1, to = 0) {
      const r = el.getBoundingClientRect();
      return clamp((from - r.top / vh) / (from - to));
    },
    pin(section, draw) {
      let top = 0, run = 1, last = -1;
      const fn = y => {
        const p = mq.matches ? 1 : clamp((y - top) / run);
        if (p === last) return;
        last = p; draw(p);
      };
      fn.measure = () => { top = section.getBoundingClientRect().top + scrollY; run = Math.max(1, section.offsetHeight - vh); last = -1; };
      site.onFrame(fn);
      mq.addEventListener('change', () => { fn.measure(); fn(scrollY, vh); });
      return () => site.offFrame(fn);
    },
    drift(el, px) {
      // progress is read from where the element would be untransformed (its rect minus the offset written last
      // frame), so the value never feeds back: the same scrollY gives the same pixel going down and coming up
      el.classList.add('fx');
      let cur = 0;
      const fn = () => {
        if (mq.matches) { cur = 0; el.style.transform = ''; return; }
        const top = el.getBoundingClientRect().top - cur;
        const p = clamp((1.1 - top / vh) / 1.3);
        cur = +(px * (1 - p)).toFixed(1);
        el.style.transform = `translate3d(0,${cur}px,0)`;
      };
      site.onFrame(fn);
      return () => { site.offFrame(fn); cur = 0; el.style.transform = ''; };
    },
    track(el, from, to, draw) {
      let last = -1;
      const fn = () => {
        const p = mq.matches ? 1 : site.progress(el, from, to);
        if (p === last) return;
        last = p; draw(p, el);
      };
      site.onFrame(fn);
      const re = () => { last = -1; fn(); };
      mq.addEventListener('change', re);
      return () => { site.offFrame(fn); mq.removeEventListener('change', re); };
    },
    prop(el, from, to, name = '--p') {
      return site.track(el, from, to, p => el.style.setProperty(name, p.toFixed(4)));
    },
    move(el, x, y, from = 1, to = .6) {
      // as drift: the vertical offset written last frame is taken off the rect before progress is read, so a
      // piece that travels in y is exactly reversible too
      el.classList.add('fx');
      let cy = 0, last = -1;
      const fn = () => {
        if (mq.matches) { cy = 0; last = -1; el.style.transform = ''; return; }
        const top = el.getBoundingClientRect().top - cy;
        const p = clamp((from - top / vh) / (from - to));
        if (p === last) return;
        last = p;
        const e = ease(p);
        cy = +(y * (1 - e)).toFixed(1);
        el.style.transform = `translate3d(${(x * (1 - e)).toFixed(1)}px,${cy}px,0)`;
      };
      site.onFrame(fn);
      const re = () => { last = -1; fn(); };
      mq.addEventListener('change', re);
      return () => { site.offFrame(fn); mq.removeEventListener('change', re); el.style.transform = ''; };
    },
    shelve(row, items, stagger = .14) {
      const list = [...(items || row.children)];
      if (!list.length) return () => {};
      list.forEach(el => el.classList.add('set', 'fx'));
      const span = 1 - stagger * (list.length - 1);
      const fn = (y, vh) => {
        if (mq.matches) { list.forEach(el => el.style.removeProperty('--set')); return; }
        const r = row.getBoundingClientRect();
        // set down as the row's foot enters at the bottom of the viewport, all standing by the time it is 72% of the way up
        const base = (vh - r.bottom) / (vh * .28);
        list.forEach((el, i) => el.style.setProperty('--set', clamp((base - i * stagger) / span).toFixed(4)));
      };
      site.onFrame(fn);
      mq.addEventListener('change', () => fn(scrollY, vh));
      return () => { site.offFrame(fn); list.forEach(el => el.style.removeProperty('--set')); };
    }
  };
  window.site = site;

  /* ---- the register: section titles print with a second impression that comes into register as they rise ----
     The covers' titles are rough, speckled print. Each h2.cap (and any .cap[data-register]) gets data-print = its
     text; css/site.css draws it again in ::after, masked with the same speckle, offset .055em up and left, fading
     as --reg goes 0 to 1 while the heading rises from 96% to 62% of the viewport. Headings inside a pinned act, or
     marked data-register="off", or not laid out (visually hidden), are left alone. */
  const regs = [...document.querySelectorAll('main h2.cap, main .cap[data-register]')].filter(h =>
    h.dataset.register !== 'off' && !h.closest('[data-pin], .hero, .dig') && h.getBoundingClientRect().width > 10 && h.textContent.trim());
  // data-register="low" (the big dates, which sit low in the first frame): comes into register sooner, from the
  // bottom edge to 84% of the viewport, so a date already on screen at load reads as printed
  site.register = h => {
    if (h.classList.contains('reg')) return;
    h.dataset.print = h.textContent.trim();
    h.classList.add('reg');
    const low = h.dataset.register === 'low';
    site.prop(h, low ? 1 : .96, low ? .84 : .62, '--reg');
  };
  regs.forEach(site.register);

  /* ---- book to book: Previous comes in from the left, Next from the right, as the links rise ---- */
  document.querySelectorAll('.nextprev').forEach(nav => {
    const prev = nav.querySelector('a[rel="prev"]'), next = nav.querySelector('a[rel="next"]');
    if (prev) site.move(prev, -14, 0, 1, .7);
    if (next) site.move(next, 14, 0, 1, .7);
  });

  /* ---- reduced motion: html.still, kept live ---- */
  const setStill = () => html.classList.toggle('still', mq.matches);
  setStill(); mq.addEventListener('change', setStill);

  /* ---- current page in the spine and the sheet ---- */
  const here = location.pathname.replace(/index\.html$/, '');
  document.querySelectorAll('.spine a, .sheet a').forEach(a => {
    const there = new URL(a.getAttribute('href'), location.href);
    if (there.hash || there.pathname.replace(/index\.html$/, '') !== here) return;
    a.setAttribute('aria-current', 'page');
  });
  // the three book pages without a link of their own: the Books link is marked (also hard-coded in their nav for no-JS)
  if (/\/(the-birder|flower-gatherers|telling-tales-in-nature)\/$/.test(here)) {
    document.querySelectorAll('.spine a[href$="#books"], .sheet a[href$="#books"]').forEach(a => { a.classList.add('on'); a.setAttribute('aria-current', 'true'); });
  }

  /* ---- the contents sheet on phones ---- */
  const tab = document.querySelector('.tab'), sheet = document.querySelector('.sheet');
  if (tab && sheet) {
    let opener = null;
    const setOpen = o => {
      sheet.classList.toggle('open', o);
      document.body.classList.toggle('sheet-open', o);
      tab.setAttribute('aria-expanded', String(o));
      if (o) { opener = document.activeElement; (sheet.querySelector('.x') || sheet.querySelector('a')).focus(); }
      else { (opener && opener.focus ? opener : tab).focus(); opener = null; }
    };
    tab.addEventListener('click', () => setOpen(!sheet.classList.contains('open')));
    sheet.addEventListener('click', e => { if (e.target.closest('.x') || e.target.closest('a')) setOpen(false); });
    addEventListener('keydown', e => {
      if (!sheet.classList.contains('open')) return;
      if (e.key === 'Escape') { setOpen(false); return; }
      if (e.key === 'Tab') { // keep focus inside the sheet
        const f = [...sheet.querySelectorAll('a, button')].filter(el => el.offsetParent !== null);
        if (!f.length) return;
        const first = f[0], last = f[f.length - 1];
        if (e.shiftKey && document.activeElement === first) { last.focus(); e.preventDefault(); }
        else if (!e.shiftKey && document.activeElement === last) { first.focus(); e.preventDefault(); }
      }
    });
    matchMedia('(min-width: 900px)').addEventListener('change', e => { if (e.matches) setOpen(false); });
  }

  /* ---- events: blocks with data-date="YYYY-MM-DD" drop to the Past list once the date has gone ----
     Markup: a list with data-events (what is coming), optionally a wrapper [data-past-wrap] holding a list
     [data-past] (hidden until something lands in it), and optionally [data-when-empty] shown when nothing is left. */
  const today = new Date(); today.setHours(0, 0, 0, 0);
  document.querySelectorAll('[data-events]').forEach(list => {
    const scope = list.closest('[data-events-scope]') || document;
    const past = scope.querySelector('[data-past]'), wrap = scope.querySelector('[data-past-wrap]'), empty = scope.querySelector('[data-when-empty]');
    const gone = [...list.querySelectorAll(':scope > [data-date]')].filter(li => {
      const d = li.dataset.date.split('-').map(Number);
      if (d.length < 3 || d.some(isNaN)) return false;
      const until = new Date(d[0], d[1] - 1, d[2]); // the event counts as current for the whole of its day
      return until < today;
    });
    gone.forEach(li => { li.classList.add('past'); if (past) past.prepend(li); else li.remove(); });
    if (wrap) wrap.hidden = !(past && past.children.length);
    if (empty) empty.hidden = list.querySelectorAll(':scope > [data-date]').length > 0;
  });
})();
