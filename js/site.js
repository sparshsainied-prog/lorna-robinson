/* lornarobinson.uk: shared script for every page.
   Page builders: do not edit this file. Page scripts go in js/<page>.js and use window.site (API below).

   window.site
     .still            true when the reader prefers reduced motion (tracked live)
     .clamp(v)         0..1
     .ease(t)          smoothstep
     .easeIn(t)        t*t
     .onFrame(fn)      fn(y, vh) once per frame when the page has scrolled or resized (one rAF-throttled listener)
     .offFrame(fn)
     .progress(el, from, to)
                       0..1 for where el is in the viewport: 0 when el's top is `from` viewport-heights below the
                       top edge, 1 when it is `to` viewport-heights. Defaults: from 1 (just entering), to 0 (at the top).
     .pin(section, fn) for a tall section with a sticky stage inside: fn(p) with p = scrolled / (height - vh), 0..1,
                       called only when p changes; under reduced motion fn(1) is called once and never again.
     .drift(el, px)    the element eases `px` pixels (negative = upward) across its travel through the viewport
   Under reduced motion, or without JavaScript, css/site.css freezes .fx elements at their finished state. */
(() => {
  const html = document.documentElement;
  html.classList.add('js');
  const mq = matchMedia('(prefers-reduced-motion: reduce)');
  const clamp = v => v < 0 ? 0 : v > 1 ? 1 : v;
  const ease = t => t * t * (3 - 2 * t);
  const easeIn = t => t * t;

  /* ---- one scroll listener for the page ---- */
  const subs = new Set();
  let ticking = false, vh = innerHeight;
  function frame() {
    ticking = false;
    const y = scrollY;
    subs.forEach(fn => fn(y, vh));
  }
  function ask() { if (!ticking) { ticking = true; requestAnimationFrame(frame); } }
  addEventListener('scroll', ask, { passive: true });
  addEventListener('resize', () => { vh = innerHeight; subs.forEach(fn => fn.measure && fn.measure()); ask(); });
  addEventListener('load', () => { subs.forEach(fn => fn.measure && fn.measure()); ask(); });

  const site = {
    get still() { return mq.matches; },
    clamp, ease, easeIn,
    onFrame(fn) { subs.add(fn); if (fn.measure) fn.measure(); fn(scrollY, vh); },
    offFrame(fn) { subs.delete(fn); },
    progress(el, from = 1, to = 0) {
      const r = el.getBoundingClientRect();
      return clamp((from - r.top / vh) / (from - to));
    },
    pin(section, draw) {
      let top = 0, run = 1, last = -1;
      const fn = y => {
        const p = mq.matches ? 1 : clamp((y - top) / run);
        if (Math.abs(p - last) < .0004) return;
        last = p; draw(p);
      };
      fn.measure = () => { top = section.getBoundingClientRect().top + scrollY; run = Math.max(1, section.offsetHeight - vh); last = -1; };
      site.onFrame(fn);
      mq.addEventListener('change', () => { fn.measure(); fn(scrollY, vh); });
      return () => site.offFrame(fn);
    },
    drift(el, px) {
      el.classList.add('fx');
      const fn = () => {
        if (mq.matches) { el.style.transform = ''; return; }
        const p = site.progress(el, 1.1, -.2);
        el.style.transform = `translate3d(0,${(px * (1 - p)).toFixed(1)}px,0)`;
      };
      site.onFrame(fn);
      return () => { site.offFrame(fn); el.style.transform = ''; };
    }
  };
  window.site = site;

  /* ---- reduced motion: html.still, kept live ---- */
  const setStill = () => html.classList.toggle('still', mq.matches);
  setStill(); mq.addEventListener('change', setStill);

  /* ---- current page in the spine and the sheet ---- */
  const here = location.pathname.replace(/index\.html$/, '');
  document.querySelectorAll('.spine a, .sheet a').forEach(a => {
    const there = new URL(a.getAttribute('href'), location.href);
    if (there.hash || there.pathname.replace(/index\.html$/, '') !== here) return;
    a.setAttribute('aria-current', 'page');
  });
  // the three book pages without a link of their own: the Books link is marked (also hard-coded in their nav for no-JS)
  if (/\/(the-birder|flower-gatherers|telling-tales-in-nature)\/$/.test(here)) {
    document.querySelectorAll('.spine a[href$="#books"], .sheet a[href$="#books"]').forEach(a => { a.classList.add('on'); a.setAttribute('aria-current', 'true'); });
  }

  /* ---- the contents sheet on phones ---- */
  const tab = document.querySelector('.tab'), sheet = document.querySelector('.sheet');
  if (tab && sheet) {
    let opener = null;
    const setOpen = o => {
      sheet.classList.toggle('open', o);
      document.body.classList.toggle('sheet-open', o);
      tab.setAttribute('aria-expanded', String(o));
      if (o) { opener = document.activeElement; (sheet.querySelector('.x') || sheet.querySelector('a')).focus(); }
      else { (opener && opener.focus ? opener : tab).focus(); opener = null; }
    };
    tab.addEventListener('click', () => setOpen(!sheet.classList.contains('open')));
    sheet.addEventListener('click', e => { if (e.target.closest('.x') || e.target.closest('a')) setOpen(false); });
    addEventListener('keydown', e => {
      if (!sheet.classList.contains('open')) return;
      if (e.key === 'Escape') { setOpen(false); return; }
      if (e.key === 'Tab') { // keep focus inside the sheet
        const f = [...sheet.querySelectorAll('a, button')].filter(el => el.offsetParent !== null);
        if (!f.length) return;
        const first = f[0], last = f[f.length - 1];
        if (e.shiftKey && document.activeElement === first) { last.focus(); e.preventDefault(); }
        else if (!e.shiftKey && document.activeElement === last) { first.focus(); e.preventDefault(); }
      }
    });
    matchMedia('(min-width: 900px)').addEventListener('change', e => { if (e.matches) setOpen(false); });
  }

  /* ---- events: blocks with data-date="YYYY-MM-DD" drop to the Past list once the date has gone ----
     Markup: a list with data-events (what is coming), optionally a wrapper [data-past-wrap] holding a list
     [data-past] (hidden until something lands in it), and optionally [data-when-empty] shown when nothing is left. */
  const today = new Date(); today.setHours(0, 0, 0, 0);
  document.querySelectorAll('[data-events]').forEach(list => {
    const scope = list.closest('[data-events-scope]') || document;
    const past = scope.querySelector('[data-past]'), wrap = scope.querySelector('[data-past-wrap]'), empty = scope.querySelector('[data-when-empty]');
    const gone = [...list.querySelectorAll(':scope > [data-date]')].filter(li => {
      const d = li.dataset.date.split('-').map(Number);
      if (d.length < 3 || d.some(isNaN)) return false;
      const until = new Date(d[0], d[1] - 1, d[2]); // the event counts as current for the whole of its day
      return until < today;
    });
    gone.forEach(li => { li.classList.add('past'); if (past) past.prepend(li); else li.remove(); });
    if (wrap) wrap.hidden = !(past && past.children.length);
    if (empty) empty.hidden = list.querySelectorAll(':scope > [data-date]').length > 0;
  });
})();
